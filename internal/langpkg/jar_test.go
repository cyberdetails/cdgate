func mkzip(t *testing.T, files ...[2]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	for _, f := range files {
		fw, err := w.Create(f[0])
		if err != nil {
			t.Fatal(err)
		}
		if _, err := fw.Write([]byte(f[1])); err != nil {
			t.Fatal(err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func pomProps(g, a, v string) string {
	return "#Generated by Maven\ngroupId=" + g + "\nartifactId=" + a + "\nversion=" + v + "\n"
}

func TestReadJar(t *testing.T) {
	inner := mkzip(t, [2]string{"META-INF/maven/org.yaml/snakeyaml/pom.properties", pomProps("org.yaml", "snakeyaml", "1.33")})
	noPom := mkzip(t, [2]string{"META-INF/MANIFEST.MF", "Manifest-Version: 1.0\r\nImplementation-Title: kotlin-stdlib\r\nImplementation-Vendor-Id: org.jetbrains\r\nImplementation-Version: 1.9.0\r\n"})
	bare := mkzip(t, [2]string{"a/B.class", "x"})
	app := mkzip(t,
		[2]string{"META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nMain-Class: x\n"},
		[2]string{"META-INF/maven/com.acme/shaded-dep/pom.properties", pomProps("com.acme", "shaded-dep", "2.0")},
		[2]string{"BOOT-INF/lib/snakeyaml-1.33.jar", string(inner)},
		[2]string{"BOOT-INF/lib/kotlin-stdlib-1.9.0.jar", string(noPom)},
		[2]string{"BOOT-INF/lib/plain.jar", string(bare)},
		[2]string{"BOOT-INF/lib/broken.jar", "not a zip"},
		[2]string{"BOOT-INF/lib/README.JAR", string(inner)}, // nested test is case-sensitive: not an archive
	)
	j := ReadJar(app, "app/app.jar")
	got := map[string]string{}
	for _, p := range j.Packages {
		got[p.Name] = p.Version + " @" + p.FilePath
	}
	want := map[string]string{
		"com.acme:shaded-dep": "2.0 @app/app.jar",
		"org.yaml:snakeyaml":  "1.33 @app/app.jar/BOOT-INF/lib/snakeyaml-1.33.jar",
	}
	if len(got) != len(want) {
		t.Errorf("%v", got)
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s: %q want %q", k, got[k], v)
		}
	}
	sum := sha1.Sum(noPom)
	if len(j.Unknown) != 1 || j.Unknown[0].Hint != "org.jetbrains:kotlin-stdlib:1.9.0" ||
		j.Unknown[0].SHA1 != hex.EncodeToString(sum[:]) || j.Unknown[0].FilePath != "app/app.jar/BOOT-INF/lib/kotlin-stdlib-1.9.0.jar" {
		t.Errorf("unknown %+v", j.Unknown)
	}
	// app.jar itself and plain.jar: no pom.properties matching their names, no hints
	if j.NoIdentity != 2 || j.Err != "" {
		t.Errorf("noIdentity %d err %q", j.NoIdentity, j.Err)
	}

	// versioned file name, no manifest: artifactId:version hint
	j = ReadJar(bare, "lib/commons-text-1.9.jar")
	if len(j.Unknown) != 1 || j.Unknown[0].Hint != "commons-text:1.9" {
		t.Errorf("file name hint %+v", j.Unknown)
	}
	// pom.properties matching the file name: identified, nothing unknown
	j = ReadJar(inner, "lib/snakeyaml-1.33.jar")
	if len(j.Packages) != 1 || len(j.Unknown) != 0 || j.NoIdentity != 0 {
		t.Errorf("matched %+v", j)
	}
	// outer archive unreadable: nothing kept, error reported
	j = ReadJar([]byte("nope"), "x.jar")
	if j.Err == "" || len(j.Packages) != 0 {
		t.Errorf("broken outer %+v", j)
	}
	if !IsJar("A.JAR") || !IsJar("x.par") || IsJar("x.zip") || isArtifact("A.JAR") || isArtifact("x.par") {
		t.Error("extension rules")
	}
}

