func TestManifest(t *testing.T) {
	m, err := parseManifestMainSection(strings.NewReader(
		"Manifest-Version: 1.0\rBundle-SymbolicName: org.apache.common\r\n s.lang3\nBundle-Name: x\n" +
			"Implementation-Version: %VERSION%\nBundle-Version: 3.12.0\n\nImplementation-Title: second-section\n"))
	if err != nil {
		t.Fatal(err)
	}
	p := m.properties("f.jar")
	// continuation joins "org.apache.commons.lang3" (a lone CR and CRLF end lines);
	// group is the part before the last dot;
	// "%..." values are ignored; parsing stops at the first empty line
	if p.groupID != "org.apache.commons" || p.artifactID != "x" || p.version != "3.12.0" {
		t.Errorf("%+v", p)
	}
}

func TestAnalyzeJars(t *testing.T) {
	src := memSource{jars: map[string]*Jar{
		"app/a.jar":             {Packages: []JarPackage{{"g:a", "1.0", "app/a.jar"}, {"g:n", "2.0", "app/a.jar/lib/n.jar"}}},
		"app/k.jar":             {Unknown: []JarUnknown{{FilePath: "app/k.jar", SHA1: "ab", Hint: "org.jetbrains:kotlin-stdlib:1.9.0"}}, NoIdentity: 2},
		"usr/share/java/os.jar": {Packages: []JarPackage{{"g:os", "1", "usr/share/java/os.jar"}}},
		"app/big.jar":           {TooLarge: true},
		"app/bad.jar":           {Err: "zip error"},
		"app/evil.jar":          {Unknown: []JarUnknown{{FilePath: "app/evil.jar", SHA1: "cd", Hint: "g:\x1b[31mred:1"}}},
		"app/huge.jar":          {Unknown: []JarUnknown{{FilePath: "app/huge.jar", SHA1: "ef", Hint: strings.Repeat("a", 215)}}},
	}}
	r := Analyze(src, map[string]bool{"usr/share/java/os.jar": true})
	got := map[string]string{}
	for _, p := range r.Packages {
		got[p.Name] = p.Ecosystem + " " + p.Version + " " + p.Source
	}
	if len(got) != 2 || got["g:a"] != "Maven 1.0 app/a.jar" || got["g:n"] != "Maven 2.0 app/a.jar/lib/n.jar" {
		t.Errorf("packages %v", got)
	}
	why := map[string]string{}
	for _, u := range r.Unchecked {
		why[u.Source] = u.UncheckedReason + " " + u.Name + " " + u.Version
	}
	if why["app/k.jar"] != JarNeedsJavaDB+" org.jetbrains:kotlin-stdlib:1.9.0 sha1:ab" || !strings.HasPrefix(why["app/big.jar"], JarTooLarge) ||
		!strings.HasPrefix(why["app/bad.jar"], JarUnreadable) || len(why) != 5 ||
		why["app/evil.jar"] != JarNeedsJavaDB+" evil.jar sha1:cd" || why["app/huge.jar"] != JarNeedsJavaDB+" huge.jar sha1:ef" {
		t.Errorf("unchecked %v", why)
	}
	if r.Skipped["installed_by_os_package"] != 1 || r.Skipped["java_archive_without_identity"] != 2 {
		t.Errorf("skipped %v", r.Skipped)
	}
}

// Rules checked against trivy 00b7394 pkg/dependency/parser/java/jar/parse.go.
func TestJarTrivyRules(t *testing.T) {
	long := "groupId=" + strings.Repeat("x", 70000) + "\n" // longer than bufio.Scanner's token: scan error
	snake := [2]string{"META-INF/maven/org.yaml/snakeyaml/pom.properties", pomProps("org.yaml", "snakeyaml", "1.33")}

	// pom.properties must match the file's artifactId AND version to identify it
	j := ReadJar(mkzip(t, snake), "lib/snakeyaml-1.32.jar")
	if len(j.Packages) != 1 || len(j.Unknown) != 1 || j.Unknown[0].Hint != "snakeyaml:1.32" {
		t.Errorf("version mismatch %+v", j)
	}
	// incomplete pom.properties is not a package; "versionX=" is not "version="
	j = ReadJar(mkzip(t, [2]string{"META-INF/maven/g/a/pom.properties", "groupId=g\nartifactId=a\n"},
		[2]string{"META-INF/maven/g/b/pom.properties", "groupId=g\nartifactId=b\nversion=1\nversionSuffix=bad\n"}), "x.jar")
	if len(j.Packages) != 1 || j.Packages[0] != (JarPackage{"g:b", "1", "x.jar"}) {
		t.Errorf("pom rules %+v", j.Packages)
	}
	// zip slip: an entry leaving the archive's path is skipped
	j = ReadJar(mkzip(t, [2]string{"../../evil-1.0.jar", string(mkzip(t, snake))}), "app/a.jar")
	if len(j.Packages) != 0 {
		t.Errorf("zip slip %+v", j.Packages)
	}
	// a nested archive that fails adds nothing, not even packages read before the failure
	bad := mkzip(t, snake, [2]string{"META-INF/maven/g/z/pom.properties", long})
	j = ReadJar(mkzip(t, [2]string{"lib/bad.jar", string(bad)}), "app/a.jar")
	if len(j.Packages) != 0 || j.Err != "" {
		t.Errorf("failed nested %+v", j)
	}
	// the outer archive failing drops everything it yielded
	j = ReadJar(bad, "app/bad.jar")
	if len(j.Packages) != 0 || !strings.Contains(j.Err, "pom.properties") {
		t.Errorf("failed outer %+v", j)
	}
	// an incomplete manifest gives no hint; the file name does
	j = ReadJar(mkzip(t, [2]string{"META-INF/MANIFEST.MF", "Implementation-Title: commons-text\n"}), "lib/commons-text-1.9.jar")
	if len(j.Unknown) != 1 || j.Unknown[0].Hint != "commons-text:1.9" {
		t.Errorf("manifest fallback %+v", j.Unknown)
	}
}

func mkzipF(f *testing.F) []byte {
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	fw, _ := w.Create("META-INF/maven/g/a/pom.properties")
	fw.Write([]byte(pomProps("g", "a", "1.0")))
	fw, _ = w.Create("META-INF/MANIFEST.MF")
	fw.Write([]byte("Implementation-Title: a\r\n x\r\nImplementation-Version: 1\n"))
	w.Close()
	return buf.Bytes()
}
